"""Publish Everyone Who Ever Lived to https://everyone-who-ever-lived.pages.dev.

1. Copies the game from its source in the Drive (pessoal/games/any-human-ever/) into site/ and SOURCES.md to the root.
2. Cuts the model (everything in the page's script before the UI section) into lib/model.js, so the portrait
   function recomputes exactly the life the page shows. Never edit lib/model.js by hand.
3. Runs `wrangler pages deploy` from this folder, so the functions and their bindings (D1, KV, Workers AI) go with the page.
4. Prints the git status; committing and pushing the GitHub copy stays a separate, manual step.

Needs the wrangler login done once on this machine by Daniel (`npx wrangler login`). The script never handles a token.
Usage: python publish.py [--preview NAME] [--model-only]
  --preview NAME  publishes to NAME.everyone-who-ever-lived.pages.dev (same database, same portrait store)
  --model-only    copies the page and rebuilds lib/model.js without deploying (for `wrangler pages dev`)
"""
import argparse
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = Path.home() / "Meu Drive" / "Claude Cowork" / "pessoal" / "games" / "any-human-ever"
PROJECT = "everyone-who-ever-lived"
WRANGLER = "wrangler@4.152.0"
UI_MARKER = "UI: hash state, reveal sequence"
EXPORTS = ["drawLife", "parseLifeId", "lifeId", "customRange", "modeRange", "portraitPrompt", "portraitAge",
           "yearLabel", "totals", "PORTRAIT_VERSION", "AHE_DATA_VERSION"]


def build_model(html: str) -> str:
    start = html.index("<script>") + len("<script>")
    ui = html.index(UI_MARKER, start)
    end = html.rindex("/* ====", start, ui)      # the banner comment that opens the UI section
    body = html[start:end]
    for name in EXPORTS:
        if not re.search(r"\b(function|const)\s+" + name + r"\b", body):
            sys.exit(f"build_model: {name} not found in the model section of index.html")
    head = ("// GENERATED by publish.py from site/index.html (the model section of its script). Do not edit.\n"
            "// The portrait function imports it so the server draws exactly the life the page shows.\n")
    return head + body + "\nexport { " + ", ".join(EXPORTS) + " };\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", metavar="NAME", help="branch alias for a test deploy instead of production")
    ap.add_argument("--model-only", action="store_true", help="copy the page and rebuild lib/model.js, no deploy")
    args = ap.parse_args()

    shutil.copy2(SOURCE / "index.html", ROOT / "site" / "index.html")
    shutil.copy2(SOURCE / "SOURCES.md", ROOT / "SOURCES.md")
    (ROOT / "lib").mkdir(exist_ok=True)
    html = (ROOT / "site" / "index.html").read_text(encoding="utf-8")
    (ROOT / "lib" / "model.js").write_text(build_model(html), encoding="utf-8", newline="\n")
    print("lib/model.js rebuilt")
    if args.model_only:
        return
    branch = args.preview or "main"
    npx = shutil.which("npx") or shutil.which("npx.cmd")
    cmd = [npx, "--yes", WRANGLER, "pages", "deploy", "--project-name", PROJECT, "--branch", branch, "--commit-dirty=true"]
    p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace")
    out = (p.stdout + p.stderr).encode("ascii", "replace").decode("ascii")   # the Windows console chokes on wrangler's emoji
    print(out[-1500:])
    if p.returncode:
        sys.exit(p.returncode)
    print(subprocess.run(["git", "status", "-s"], cwd=ROOT, capture_output=True, text=True).stdout)


if __name__ == "__main__":
    main()
